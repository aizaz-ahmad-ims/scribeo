def compile_note(subj, obj, assess, plan):
    note = f"""SCRIBEO — MEDICAL NOTE
{'=' * 50}

SUBJECTIVE:
{subj or 'Not documented.'}

OBJECTIVE:
{obj or 'Not documented.'}

ASSESSMENT:
{assess or 'Not documented.'}

PLAN:
{plan or 'Not documented.'}

{'=' * 50}
Generated by Scribeo
For demo purposes only — always verify with a licensed clinician.
"""
    return note


def save_note(subj, obj, assess, plan):
    content = compile_note(subj, obj, assess, plan)
    file_path = "/tmp/scribeo_note.txt"
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(content)
    return file_path


