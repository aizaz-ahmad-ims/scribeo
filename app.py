# --- SETUP ---
groq_client = Groq(api_key=os.environ.get("GROQ_API_KEY"))

system_prompt = """You are a medical scribe assistant.
Convert a doctor-patient transcript into a structured SOAP note.

Rules:
- Output ONLY the SOAP note. No explanations.
- Preserve all medical facts: symptoms, durations, dosages, drug names.
- Correct obvious misspellings of drug names (e.g., "penadol" -> "Paracetamol").
- Use clinical language, not conversational language.
- If a section has no information, write "Not documented."
- Never invent facts that weren't in the transcript.

Format:
SUBJECTIVE:
[Patient's reported symptoms, duration, history]

OBJECTIVE:
[Vitals, exam findings - if mentioned]

ASSESSMENT:
[Clinical impression]

PLAN:
[Medications, tests, follow-up]
"""


def generate_note(audio_file, progress=gr.Progress()):
    if audio_file is None:
        return "Please upload or record audio.", "", "", "", ""

    time.sleep(0.5)
    sample_rate, audio_data = audio_file

    if audio_data is None or len(audio_data) == 0:
        return "No audio detected. Please try again.", "", "", "", ""

    progress(0.1, desc="Processing audio...")

    if len(audio_data.shape) > 1:
        audio_data = audio_data.mean(axis=1)

    if audio_data.dtype != np.float32:
        audio_data = audio_data.astype(np.float32) / np.iinfo(audio_data.dtype).max

    temp_path = "/tmp/audio.wav"
    sf.write(temp_path, audio_data, sample_rate)

    progress(0.3, desc="Transcribing...")
    with open(temp_path, "rb") as f:
        transcription = groq_client.audio.transcriptions.create(
            file=("audio.wav", f.read()),
            model="whisper-large-v3-turbo",
            language="ur",
            response_format="text"
        )
    transcript = transcription if isinstance(transcription, str) else transcription.text

    if not transcript.strip():
        return "No speech detected. Please try again.", "", "", "", ""

    progress(0.6, desc="Generating medical note...")
    response = groq_client.chat.completions.create(
        model="openai/gpt-oss-120b",
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": f"Convert this transcript:\n\n{transcript}"}
        ],
        temperature=0.1
    )
    soap_note = response.choices[0].message.content

    sections = {"S": "", "O": "", "A": "", "P": ""}
    current = None
    for line in soap_note.split("\n"):
        upper = line.strip().upper()
        if upper.startswith("SUBJECTIVE"):
            current = "S"
        elif upper.startswith("OBJECTIVE"):
            current = "O"
        elif upper.startswith("ASSESSMENT"):
            current = "A"
        elif upper.startswith("PLAN"):
            current = "P"
        elif current:
            sections[current] += line + "\n"

    progress(1.0, desc="Done")

    return (
        transcript,
        sections["S"].strip(),
        sections["O"].strip(),
        sections["A"].strip(),
        sections["P"].strip()
    )


def check_audio_ready(audio):
    if audio is None:
        return gr.update(interactive=False)
    sample_rate, audio_data = audio
    if audio_data is None or len(audio_data) == 0:
        return gr.update(interactive=False)
    return gr.update(interactive=True)


